// 只测纯前端几何、编辑历史和采集门槛，不连接机器人或后端。
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../static/js/taught_geometry.js', import.meta.url), 'utf8');
const G = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const pts = [{ x:0,y:0,continuous_id:0 }, { x:3,y:4,continuous_id:0 }, { x:50,y:40,continuous_id:1 }, { x:53,y:44,continuous_id:1 }];
assert.equal(G.taughtLength(pts), 10, '断口不算成行驶距离');
assert.deepEqual(G.continuousRuns(pts).map(r => r.length), [2,2], '断线后分别画线');
assert.throws(() => G.cleanTaughtPoints([{ x:null, y:1 }]), /坐标/);
assert.throws(() => G.cleanTaughtPoints([{ x:1, y:Infinity }]), /坐标/);
assert.throws(() => G.cleanTaughtPoints({}), /数组/);
assert.equal(G.cleanTaughtPoints([]).length, 0, '无轨迹也能打开编辑器');
const view = { cx:5, cy:-2, s:37 };
for (const angle of [0,Math.PI/2,-Math.PI/2,Math.PI,0.72]){
  const point = { x:2.3, y:-4.1 };
  const px = G.taughtWorldToScreen(point, 930, 640, view, angle);
  const got = G.taughtScreenToWorld(px.x, px.y, 930, 640, view, angle);
  assert.ok(Math.hypot(got.x-point.x,got.y-point.y) < 1e-10, '显示旋转不会改变保存的世界坐标');
}
const grid = { w:100,h:60,res:.05,ox:2,oy:3,oyaw:Math.PI/2 };
assert.equal(G.taughtInMap({x:1,y:4},grid), true);
assert.equal(G.taughtInMap({x:3,y:4},grid), false, '底图旋转要先反变换再判断边界');
const h = G.createTaughtHistory([{ x:1,y:2 }]);
h.commit([{x:3,y:4}]); h.commit([{x:5,y:6}]);
assert.equal(h.undo()[0].x, 3); assert.equal(h.redo()[0].x, 5);
h.undo(); h.commit([{x:7,y:8}]);
assert.equal(h.canRedo, false, '新修改会丢弃被撤销的分支');
assert.equal(h.undo()[0].x, 3);
const doc = { map:'map_a',revision:1,map_token:'token',points:pts,check:{ok:true,state:'ready'},capture:null,state:'ready',executable:true };
const store = { source:'ros',link:{ok:true},mapCurrent:'map_a',profiles:{mapping:'stop'},task:{type:'idle'},estop:false };
assert.equal(G.taughtStartBlocker(store,doc,'replace'), '');
assert.match(G.taughtStartBlocker(store,{...doc,check:{state:'ready'}},'replace'), /自检/);
assert.match(G.taughtStartBlocker(store,{...doc,map:'map_b'},'replace'), /加载/);
assert.match(G.taughtStartBlocker(store,doc,'replace_segment',{start:3,end:1}), /区间/);
assert.equal(G.taughtStartBlocker(store,doc,'replace_segment',{start:0,end:3}), '');
assert.match(G.taughtStartBlocker(store,{...doc,state:'invalid',executable:false},'append'), /参考/);
assert.match(G.taughtStartBlocker(store,{...doc,capture:{state:'paused'}},'replace'), /草稿/);
assert.match(G.taughtStartBlocker({...store,profiles:{mapping:'run'}},doc,'replace'), /建图/);
const header = Buffer.from(JSON.stringify({w:2,h:3,res:.05,ox:2,oy:3,oyaw:-Math.PI/2}));
const packet = new Uint8Array(5+header.length+2); packet[0] = 1;
new DataView(packet.buffer).setUint32(1,header.length,true); packet.set(header,5); packet.set([12,13],5+header.length);
assert.equal(G.readTaughtGridFrame(packet.buffer).meta.oyaw,-Math.PI/2);
assert.deepEqual([...G.readTaughtGridFrame(packet.buffer).payload],[12,13]);
assert.throws(()=>G.readTaughtGridFrame(new Uint8Array([1,2]).buffer),/地图/);
const badPacket = packet.slice(); badPacket[0] = 7;
assert.throws(()=>G.readTaughtGridFrame(badPacket.buffer),/地图/);
const cache = {taughtByMap:{},taughtMap:'map_a'};
G.storeTaughtDocument(cache,doc); G.storeTaughtDocument(cache,{...doc,map:'map_b'});
assert.equal(cache.taught.map,'map_a','其他地图状态推送不抢占选择');
G.storeTaughtDocument(cache,{...doc,revision:0});
assert.equal(cache.taught.revision,1,'迟到旧版本不会覆盖新版本');
console.log('PASS 示教断口、非法点、旋转坐标、撤销重做与采集门槛');

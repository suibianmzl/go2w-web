import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const geometry = await readFile(new URL('../static/js/taught_geometry.js',import.meta.url),'utf8');
const url = `data:text/javascript;base64,${Buffer.from(geometry).toString('base64')}`;
const source = (await readFile(new URL('../static/js/source/mock_taught.js',import.meta.url),'utf8')).replace('../taught_geometry.js',url);
const { createMockTaught } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const mem = new Map(); globalThis.localStorage = {getItem:k=>mem.get(k),setItem:(k,v)=>mem.set(k,v)};
const store = {mapCurrent:'one',maps:[{name:'one'}],taughtByMap:{},taughtMap:'one',link:{ok:true},source:'mock',estop:false,
  robot:{x:1,y:2,th:0},profiles:{mapping:'stop'},task:{type:'idle'}};
const mock = createMockTaught(store,{prepare:()=>{},halt:()=>{}}), cmd = mock.cmd;
let d = cmd.taughtGet('one').data;
assert.match(cmd.taughtStart({map:'one',mode:'replace',expected_revision:0,map_token:d.map_token}).msg,/自检/);
assert.equal(cmd.taughtPrepare('one').ok,true);
d = cmd.taughtGet('one').data;
let r = cmd.taughtStart({map:'one',mode:'replace',expected_revision:0,map_token:d.map_token});
assert.equal(r.ok,true); const id = r.data.capture.session_id;
store.robot.x += .3; mock.tick(.2);
assert.equal(store.taught.capture.sample_count,2);
assert.equal(cmd.taughtPrepare('one').ok,false,'采样中仍不能重新准备');
assert.equal(cmd.taughtPause('stale').ok,false,'旧会话不得控制新采集');
assert.equal(cmd.taughtPause(id).ok,true);
assert.equal(cmd.taughtPrepare('one').ok,true,'暂停同图可重新准备定位');
assert.equal(store.taught.capture.session_id,id,'重新准备保留原会话');
assert.equal(store.taught.capture.state,'paused','重新准备不自动采样');
store.maps.push({name:'other'});
assert.equal(cmd.taughtPrepare('other').ok,false,'存在草稿时不可为异图准备');
store.robot.x += .3; mock.tick(.2);
assert.equal(store.taught.capture.sample_count,2,'暂停后不采样');
assert.equal(cmd.taughtResume(id).ok,false,'离断点过远不恢复');
store.robot.x -= .3; assert.equal(cmd.taughtResume(id).ok,true);
store.robot.x += .4; mock.tick(.2);
const recorded = store.taught.capture.points;
assert.notEqual(recorded[0].continuous_id,recorded.at(-1).continuous_id,'恢复后的实测断口保留');
r = cmd.taughtFinish(id); assert.equal(r.ok,true); assert.equal(r.data.revision,1); assert.equal(r.data.simulated,true);
assert.equal(cmd.taughtSave({map:'one',expected_revision:0,map_token:d.map_token,points:r.data.points}).ok,false,'保存冲突保留旧参考');
assert.equal(store.taught.revision,1);
console.log('PASS 模拟源显式准备、采样、暂停、断点门槛、过期会话和版本冲突');
